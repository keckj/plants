if (import.meta.env.DEV) {
  const seenIds = new Set()
  const validTiers = new Set(['beginner', 'intermediate', 'advanced', 'expert'])
  for (const b of boletes) {
    console.assert(b.edibility in edibilityTypes, `edibility inconnue pour ${b.id}: ${b.edibility}`)
    console.assert(!seenIds.has(b.id), `id dupliqué: ${b.id}`)
    seenIds.add(b.id)
    console.assert(validTiers.has(b.tier), `tier invalide pour ${b.id}: ${b.tier}`)
  }
}
